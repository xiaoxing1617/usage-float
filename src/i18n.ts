export const DICTS: Record<Lang, Dict> = { en, "zh-Hans": zhHans, "zh-Hant": zhHant };

/** zh-TW / zh-HK / zh-MO / zh-Hant -> Traditional; other zh -> Simplified. */
export function detectLang(): Lang {
  const l = (navigator.language || "en").toLowerCase();
  if (!l.startsWith("zh")) return "en";
  return /hant|tw|hk|mo/.test(l) ? "zh-Hant" : "zh-Hans";
}

/** BCP-47 tag for Intl formatting. */
export function intlLocale(lang: Lang): string {
  return lang === "en" ? "en-SG" : lang === "zh-Hant" ? "zh-TW" : "zh-SG";
}

export function fmt(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
